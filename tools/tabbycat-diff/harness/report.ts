/** Renders the comparison as the committed markdown and JSON reports (deterministic: no timestamps). */
import type { Check, Classification, Discrepancy } from "./compare";

export interface FixtureReport {
  fixture: string;
  title: string;
  description: string;
  tabbycatVersion: string;
  checks: Check[];
  discrepancies: Discrepancy[];
}

const ORDER: Classification[] = [
  "unclassified",
  "CrabbyTab defect",
  "rule difference",
  "configuration difference",
  "valid alternative",
];

function cell(value: unknown, limit = 160): string {
  if (value === undefined) return "";
  const text = typeof value === "string" ? value : JSON.stringify(value);
  const clipped = text.length > limit ? `${text.slice(0, limit - 1)}…` : text;
  return clipped.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function reportJson(reports: FixtureReport[]) {
  return {
    tabbycatVersion: [...new Set(reports.map((report) => report.tabbycatVersion))].join(", "),
    fixtures: reports.map((report) => ({
      fixture: report.fixture,
      checks: report.checks,
      discrepancies: report.discrepancies,
    })),
  };
}

export function reportMarkdown(reports: FixtureReport[]): string {
  const lines: string[] = [];
  const all = reports.flatMap((report) => report.discrepancies);
  const version = [...new Set(reports.map((report) => report.tabbycatVersion))].join(", ");
  lines.push("# Tabbycat differential report", "");
  lines.push(
    `Generated by \`tools/tabbycat-diff\` against Tabbycat ${version}. Regenerate with ` +
      "`TABBYCAT_DIFF_WRITE=1 npx vitest run tools/tabbycat-diff` after refreshing the golden files " +
      "(see `tools/tabbycat-diff/README.md`). Do not edit by hand.",
    ""
  );

  lines.push("## Summary", "");
  lines.push("| Fixture | Area | Checks agreed | " + ORDER.slice(1).join(" | ") + " |");
  lines.push("|---|---|---|" + ORDER.slice(1).map(() => "---").join("|") + "|");
  for (const report of reports) {
    for (const area of ["config", "standings", "draw", "break", "allocation"] as const) {
      const checks = report.checks.filter((check) => check.area === area);
      const items = report.discrepancies.filter((item) => item.area === area);
      if (checks.length === 0 && items.length === 0) continue;
      const compared = checks.reduce((sum, check) => sum + check.compared, 0);
      const agreed = checks.reduce((sum, check) => sum + check.agreed, 0);
      const counts = ORDER.slice(1).map((classification) => items.filter((item) => item.classification === classification).length || "");
      lines.push(`| ${report.fixture} | ${area} | ${compared ? `${agreed}/${compared}` : "—"} | ${counts.join(" | ")} |`);
    }
  }
  const unclassified = all.filter((item) => item.classification === "unclassified").length;
  lines.push("", unclassified ? `**${unclassified} unclassified discrepancies.**` : "Every discrepancy is classified.", "");

  for (const classification of ORDER) {
    const items = all.filter((item) => item.classification === classification);
    if (items.length === 0) continue;
    lines.push(`## ${classification[0].toUpperCase()}${classification.slice(1)} (${items.length})`, "");
    lines.push("| Discrepancy | What differs | Tabbycat | CrabbyTab | Note |");
    lines.push("|---|---|---|---|---|");
    for (const item of items) {
      const note = [item.note, item.dependsOn?.length ? `Depends on ${item.dependsOn.join(", ")}.` : ""].filter(Boolean).join(" ");
      lines.push(`| \`${item.id}\` | ${cell(item.summary)} | ${cell(item.tabbycat)} | ${cell(item.crabbytab)} | ${cell(note, 400)} |`);
    }
    lines.push("");
  }

  lines.push("## What was compared", "");
  for (const report of reports) {
    lines.push(`### ${report.fixture}: ${report.title}`, "", report.description, "");
    lines.push("| Area | Check | Agreed |", "|---|---|---|");
    for (const check of report.checks) {
      lines.push(`| ${check.area} | ${cell(check.subject, 200)} | ${check.agreed}/${check.compared} |`);
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}
